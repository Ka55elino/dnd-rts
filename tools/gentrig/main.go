// Command gentrig generates internal/fixed/trig_tables.go.
//
// The generated tables are COMMITTED and are the source of truth: the
// simulation never computes trig with floats at runtime. Regenerating on a
// different machine may differ in the last bit of a few entries (libm / FMA
// differences), which is harmless only because everyone ships the same
// committed file. Do not regenerate casually — it changes simulation results.
//
//	go run ./tools/gentrig > internal/fixed/trig_tables.go
package main

import (
	"fmt"
	"math"
	"os"
	"strings"
)

const (
	sinTableSize  = 4096 // entries per full turn
	atanTableSize = 1024 // entries over t in [0, 1]
	scale         = 1 << 16
)

func round(x float64) int64 {
	if x < 0 {
		return -int64(math.Floor(-x + 0.5))
	}
	return int64(math.Floor(x + 0.5))
}

func table(name string, n int, f func(i int) float64) string {
	var b strings.Builder
	fmt.Fprintf(&b, "var %s = [%d + 1]Fixed{\n", name, n)
	for i := 0; i <= n; i++ {
		if i%8 == 0 {
			b.WriteString("\t")
		}
		fmt.Fprintf(&b, "%d,", round(f(i)*scale))
		if i%8 == 7 || i == n {
			b.WriteString("\n")
		} else {
			b.WriteString(" ")
		}
	}
	b.WriteString("}\n")
	return b.String()
}

func main() {
	out := os.Stdout
	fmt.Fprintln(out, "// Code generated by tools/gentrig; DO NOT EDIT.")
	fmt.Fprintln(out, "// Committed lookup tables: the source of truth for deterministic trig.")
	fmt.Fprintln(out)
	fmt.Fprintln(out, "package fixed")
	fmt.Fprintln(out)
	fmt.Fprintf(out, "const (\n\tsinTableSize  = %d\n\tatanTableSize = %d\n)\n\n", sinTableSize, atanTableSize)
	fmt.Fprintln(out, "// sinTable[i] = sin(2π·i/sinTableSize), one extra entry for interpolation.")
	fmt.Fprint(out, table("sinTable", sinTableSize, func(i int) float64 {
		return math.Sin(2 * math.Pi * float64(i) / sinTableSize)
	}))
	fmt.Fprintln(out)
	fmt.Fprintln(out, "// atanTable[i] = atan(i/atanTableSize), one extra entry for interpolation.")
	fmt.Fprint(out, table("atanTable", atanTableSize, func(i int) float64 {
		return math.Atan(float64(i) / atanTableSize)
	}))
}
