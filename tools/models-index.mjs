// Shared by tools/vatbake and tools/meshbake: keeps frontend/public/models/index.json,
// the list of every baked model (the Model Overview screen reads it; a built game
// can't list a directory).
import fs from "node:fs";
import path from "node:path";

/**
 * Replaces the entries of one model type ("vat" | "static") with `ids` that have
 * been baked (their model.json exists), keeping the other type's entries.
 */
export function updateModelsIndex(repo, type, ids) {
  const dir = path.join(repo, "frontend/public/models");
  const file = path.join(dir, "index.json");
  let models = [];
  try {
    models = JSON.parse(fs.readFileSync(file, "utf8")).models ?? [];
  } catch {
    // first run
  }
  const mine = ids.filter((id) => fs.existsSync(path.join(dir, id, "model.json"))).map((id) => ({ id, type }));
  // Keep entries written by the other tool (vatbake / meshbake) while their model still exists.
  const keep = (m) => !ids.includes(m.id) && (m.type !== type || fs.existsSync(path.join(dir, m.id, "model.json")));
  models = [...models.filter(keep), ...mine].sort((a, b) => a.id.localeCompare(b.id));
  const index = {
    $comment: "Generated by tools/vatbake and tools/meshbake: every baked model. vat = animated (VatModel), static = LODs (StaticModel).",
    models,
  };
  fs.writeFileSync(file, JSON.stringify(index, null, 2) + "\n");
}
